"""Generate Appendix B (claims ledger) from claims.json.

The ledger is generated, never hand-written: a claim table typed by hand is
exactly the kind of thing that drifts from the registry the moment a deadline
hits. ``tests/test_guards.py`` regenerates it and compares, so a stale
appendix fails the suite.

Usage:  python tools/gen_claims_tex.py [--out paper/sections/claims_ledger.tex]
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

SPECIAL = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


def esc(text: str) -> str:
    return "".join(SPECIAL.get(ch, ch) for ch in (text or ""))


def render(data: dict) -> str:
    claims = data.get("claims", [])
    by_status: dict[str, int] = {}
    for c in claims:
        by_status[c.get("status", "?")] = by_status.get(c.get("status", "?"), 0) + 1
    summary = ", ".join(f"{k} {v}" for k, v in sorted(by_status.items()))

    lines = [
        "% GENERATED by tools/gen_claims_tex.py from claims.json — do not edit",
        f"% source digest date: {date.today().isoformat()}",
        r"\section{Claims Ledger}",
        r"\label{app:claims}",
        "",
        r"Every assertion this manuscript is allowed to make is registered in",
        r"\texttt{claims.json} and reproduced here mechanically. Statuses:",
        r"\texttt{measured} = a script or test in the released repository",
        r"establishes it (evidence paths listed); \texttt{planned} = the protocol",
        r"is implemented but the experiment has not been run, so no number is",
        r"reported. \texttt{tools/check\_claims.py} fails the build if a claim is",
        r"marked measured without evidence on disk, if a comparative or rate",
        r"claim lacks a control arm, or if the manuscript references an id that",
        r"is not registered here.",
        "",
        f"\\noindent\\textbf{{Summary:}} {len(claims)} claims ({esc(summary)}).",
        "",
        r"\begin{description}\small",
    ]

    for c in claims:
        cid = esc(str(c.get("id", "?")))
        status = esc(str(c.get("status", "?")))
        kind = esc(str(c.get("kind", "?")))
        lines.append(f"\\item[\\cid{{{cid}}} ({status}, {kind})] {esc(c.get('statement', ''))}")
        bits = []
        if c.get("metric"):
            bits.append(f"\\emph{{Metric:}} {esc(str(c['metric']))}")
        if c.get("control"):
            bits.append(f"\\emph{{Control:}} {esc(str(c['control']))}")
        ev = c.get("evidence") or []
        if ev:
            # \path{} is a verbatim-ish context: underscores must stay raw
            # (escaping them prints a literal backslash and kills the break
            # points), and it breaks at "/" where \texttt cannot
            bits.append("\\emph{Evidence:} "
                        + ", ".join("\\path{" + str(e) + "}" for e in ev))
        if bits:
            lines.append("\\\\ " + " --- ".join(bits))
        lines.append("")

    lines.append(r"\end{description}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="gen_claims_tex",
                                 description="render claims.json as a LaTeX appendix")
    ap.add_argument("--claims", default=str(ROOT / "claims.json"))
    ap.add_argument("--out", default=str(ROOT / "paper" / "sections" / "claims_ledger.tex"))
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the file on disk differs from the render")
    a = ap.parse_args(argv)

    text = render(json.loads(Path(a.claims).read_text(encoding="utf-8")))
    out = Path(a.out)
    if a.check:
        current = out.read_text(encoding="utf-8") if out.is_file() else ""
        if current != text:
            print(f"STALE: {out} does not match claims.json (regenerate it)")
            return 1
        print(f"OK: {out} is in sync with claims.json")
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    from bioforge_harbor.util.io import write_text_lf
    write_text_lf(out, text)
    print(f"wrote {out} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
